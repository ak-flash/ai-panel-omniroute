/* ============================================================
   AI Panel — ранняя установка темы до первой отрисовки.

   Обычный (не модульный) скрипт, подключается синхронно в <head>
   до styles.css: применяет сохранённый выбор к <html data-theme>,
   чтобы не мигало системной темой. Внешний файл вместо inline-кода —
   CSP страницы запрещает inline-скрипты (script-src 'self').
   ============================================================ */

try {
  var t = localStorage.getItem('theme');
  if (t === 'light' || t === 'dark') document.documentElement.setAttribute('data-theme', t);
} catch (e) { /* нет localStorage — останется системная тема */ }
